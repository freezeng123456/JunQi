# HELPERS for combat scenarios
# ===========================================================================


def _place_fillers(
    case: "Case",
    *,
    skip: tuple[tuple[int, int], ...] = (),
    skip_seats: tuple = (),
) -> "Case":
    """Place one surviving PAIZH on each of the four seats' home rows.

    This ensures _check_victory() does not mis-fire due to a seat having no
    live pieces left. Cells listed in `skip` (already occupied by an attacker
    / defender / other scenario piece) are not filled. Seats listed in
    `skip_seats` are skipped entirely (e.g. when the scenario places its own
    WEST defender at WEST's idx=0 cell, we still add a WEST filler at a
    different index below, so that code path is not needed in practice).
    """
    # Default fillers (all on rail / home rows, none conflicting with the
    # standard attack templates (6,10)->(5,10) / (1,9)->(0,9) / (10,10)->(11,10)).
    fillers = [
        (SOUTH,  0, PAIZH, (10, 11)),   # SOUTH idx=0
        (NORTH,  0, PAIZH, (6, 5)),     # NORTH idx=0
        (WEST, 5, PAIZH, (4, 10)),    # WEST idx=5
        (EAST,  0, PAIZH, (11, 6)),    # EAST idx=0
    ]
    for seat, idx, piece, pos in fillers:
        if seat in skip_seats:
            continue
        if pos in skip:
            continue
        case.place(seat, index=idx, piece=piece, at=pos)
    return case


