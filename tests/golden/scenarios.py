def gen_setup_validation() -> None:
    out = GOLDEN_ROOT / "setup_validation"

    # 1. All-valid: the canonical setup
    SetupCase("valid_canonical_setup") \
        .describe("The canonical valid setup for all 4 seats passes all C1-C5.") \
        .tag("C1", "C2", "C3", "C4", "C5", "valid") \
        .with_lineups(_canonical_setup()) \
        .expect_valid(valid=True, violations=()) \
        .save(out)

    # 2. C1: piece at camp index 6
    bad1 = _canonical_valid_lineup()
    bad1[6] = "PAIZH"
    bad1[0] = "NONE"  # compensate counts
    SetupCase("c1_piece_in_camp_6") \
        .describe("C1 violation: piece placed at camp index 6 (and index 0 emptied to balance).") \
        .tag("C1", "invalid") \
        .with_lineups([bad1] + [_canonical_valid_lineup()] * 3) \
        .expect_valid(valid=False, violations=("C1",)) \
        .save(out)

    # 3. C2: flag NOT in stronghold
    bad2 = _canonical_valid_lineup()
    # swap flag from 26 to 25 (non-stronghold)
    bad2[25], bad2[26] = bad2[26], bad2[25]
    SetupCase("c2_flag_not_in_stronghold") \
        .describe("C2 violation: JUNQI placed at index 25 (non-stronghold), and the original slot gets the swapped piece.") \
        .tag("C2", "invalid") \
        .with_lineups([bad2] + [_canonical_valid_lineup()] * 3) \
        .expect_valid(valid=False, violations=("C2",)) \
        .save(out)

    # 4. C3: DILEI in front row
    bad3 = _canonical_valid_lineup()
    # swap a DILEI (at 20) with index 0
    bad3[0], bad3[20] = bad3[20], bad3[0]
    SetupCase("c3_dilei_in_front_row") \
        .describe("C3 violation: DILEI placed at index 0 (front row) via swap with a ranked piece.") \
        .tag("C3", "invalid") \
        .with_lineups([bad3] + [_canonical_valid_lineup()] * 3) \
        .expect_valid(valid=False, violations=("C3",)) \
        .save(out)

    # 5. C4: ZHADAN in front row
    bad4 = _canonical_valid_lineup()
    # ZHADAN is at 5; swap with index 0
    bad4[0], bad4[5] = bad4[5], bad4[0]
    SetupCase("c4_zhadan_in_front_row") \
        .describe("C4 violation: ZHADAN placed at index 0 (front row) via swap.") \
        .tag("C4", "invalid") \
        .with_lineups([bad4] + [_canonical_valid_lineup()] * 3) \
        .expect_valid(valid=False, violations=("C4",)) \
        .save(out)

    # 6. C5: extra SILING (count=2, expected=1)
    bad5 = _canonical_valid_lineup()
    # find a GONGB (should exist) and replace with SILING
    gongb_idx = next(i for i, v in enumerate(bad5) if v == "GONGB")
    bad5[gongb_idx] = "SILING"
    SetupCase("c5_extra_siling") \
        .describe("C5 violation: SILING count = 2 (GONGB replaced with SILING). Missing 1 GONGB and excess 1 SILING.") \
        .tag("C5", "invalid") \
        .with_lineups([bad5] + [_canonical_valid_lineup()] * 3) \
        .expect_valid(valid=False, violations=("C5",)) \
        .save(out)

    # 7. Combined C1 + C3
    bad6 = _canonical_valid_lineup()
    bad6[6] = "PAIZH"       # C1
    bad6[0] = "DILEI"       # C3 + extra logic
    # original [0]="SILING" — now SILING is missing (C5 also triggered);
    # original [6]="NONE" — still 5 NONE's if we kept [0] as something else.
    # Actually by making [0]=DILEI, we've introduced: +1 DILEI, -1 SILING,
    # +1 PAIZH (at 6), -1 NONE. Counts now: DILEI=4 (was 3), SILING=0, PAIZH=4.
    # So we get C1 + C3 + C5 all. Accept that; test expect_violations accordingly.
    SetupCase("combined_c1_c3_c5") \
        .describe("Multiple-violation case: piece at camp + DILEI in front + count imbalance.") \
        .tag("C1", "C3", "C5", "invalid", "combined") \
        .with_lineups([bad6] + [_canonical_valid_lineup()] * 3) \
        .expect_valid(valid=False, violations=("C1", "C3", "C5")) \
        .save(out)

    # 8. Wrong length (LENGTH violation)
    short = _canonical_valid_lineup()[:-1]  # 29 slots
    SetupCase("length_mismatch") \
        .describe("Lineup with only 29 slots (short by 1). Rejected before C1-C5 checks.") \
        .tag("LENGTH", "invalid") \
        .with_lineups([short] + [_canonical_valid_lineup()] * 3) \
        .expect_valid(valid=False, violations=("LENGTH",)) \
        .save(out)


