def _canonical_valid_lineup() -> list[str]:
    """Produce one deterministic, rule-compliant lineup (used as a template).

    The exact placement below was chosen to be easy to mutate in C1..C5 tests.
    Camps (indices 6, 8, 12, 16, 18) are NONE.
    Flag at index 26 (stronghold). Mines at 20, 22, 24. Bombs at 5, 7.
    """
    lu: list[str | None] = [None] * SLOTS_PER_SEAT
    # Camps
    for i in (6, 8, 12, 16, 18):
        lu[i] = "NONE"
    # Flag
    lu[26] = "JUNQI"
    # Mines (all 3, all in back two rows)
    lu[20] = "DILEI"
    lu[22] = "DILEI"
    lu[24] = "DILEI"
    # Other stronghold (28) gets a non-flag piece
    lu[28] = "GONGB"
    # Bombs (not in row 0)
    lu[5] = "ZHADAN"
    lu[7] = "ZHADAN"
    # Ranked combatants
    lu[0] = "SILING"
    lu[1] = "JUNZH"
    lu[2] = "SHIZH"
    lu[3] = "SHIZH"
    lu[4] = "LVZH"
    lu[9] = "LVZH"
    lu[10] = "TUANZH"
    lu[11] = "TUANZH"
    lu[13] = "YINGZH"
    lu[14] = "YINGZH"
    lu[15] = "LIANZH"
    lu[17] = "LIANZH"
    lu[19] = "LIANZH"
    lu[21] = "PAIZH"
    lu[23] = "PAIZH"
    lu[25] = "PAIZH"
    lu[27] = "GONGB"
    lu[29] = "GONGB"
    assert all(x is not None for x in lu)
    return [x for x in lu]  # type: ignore[misc]


def _canonical_setup() -> list[list[str]]:
    return [_canonical_valid_lineup() for _ in range(4)]


